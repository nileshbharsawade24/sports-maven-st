#!/usr/bin/env node
/* Build step for academies. Run after you add, edit or delete a file in content/academies/:
       node tools/make-pages.js
   It (1) bundles content/academies/*.js into assets/js/academies.js,
       (2) writes one page per academy into /academies, and
       (3) removes pages of academies you deleted.
   Files in content/academies/ starting with "_" are ignored (templates). Order on the site = file name order. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'content', 'academies');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.js') && !f.startsWith('_')).sort();

// 1. bundle (and validate) the academy files
global.window = {};
const bundle = ['/* GENERATED by tools/make-pages.js from content/academies/*.js. Do not edit by hand. */'];
const seen = new Set();
for (const f of files) {
  const before = (global.window.ACADEMIES || []).length;
  require(path.join(dir, f));
  const added = (global.window.ACADEMIES || []).slice(before);
  if (added.length !== 1) throw new Error(`${f}: must add exactly one academy`);
  const a = added[0];
  for (const k of ['slug', 'name', 'tagline', 'about']) if (!a[k]) throw new Error(`${f}: missing "${k}"`);
  if (!/^[a-z0-9-]+$/.test(a.slug)) throw new Error(`${f}: slug "${a.slug}" must be lowercase letters, digits and dashes`);
  if (seen.has(a.slug)) throw new Error(`${f}: duplicate slug "${a.slug}"`);
  seen.add(a.slug);
  bundle.push(fs.readFileSync(path.join(dir, f), 'utf8').trimEnd());
}
fs.writeFileSync(path.join(root, 'assets/js/academies.js'), bundle.join('\n\n') + '\n');
console.log(`bundled ${files.length} academies into assets/js/academies.js`);

require(path.join(root, 'assets/js/data.js'));
const S = global.window.SITE;
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

fs.mkdirSync(path.join(root, 'academies'), { recursive: true });
const wanted = new Set();
for (const a of S.academies) {
  const file = `${a.slug}.html`;
  wanted.add(file);
  const desc = esc(`${a.tagline} ${a.about}`);
  const title = esc(`${a.name}${a.kind ? ' ' + a.kind : ''} | ${S.brand.name}`);
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${desc}">
<meta property="og:type" content="website">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${desc}">
<meta name="theme-color" content="#0b0a09">
<link rel="icon" href="../favicon.svg" type="image/svg+xml">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&amp;family=Playfair+Display:wght@500;600;700&amp;display=swap">
<link rel="stylesheet" href="../assets/css/style.css">
</head>
<body data-page="academy" data-academy="${a.slug}" data-root="..">
<header id="site-header"></header>
<main id="main"></main>
<footer id="site-footer"></footer>
<noscript><p style="padding:24px;color:#fff">Please enable JavaScript to view this page. Contact us on <a style="color:#fff" href="https://wa.me/${esc(a.whatsapp || S.contact.whatsapp)}">WhatsApp</a> or <a style="color:#fff" href="mailto:${esc(a.email || S.contact.email)}">email</a>.</p></noscript>
<script src="../assets/js/academies.js"></script>\n<script src="../assets/js/data.js"></script>
<script src="../assets/js/app.js"></script>
</body>
</html>
`;
  fs.writeFileSync(path.join(root, 'academies', file), html);
  console.log('wrote academies/' + file);
}
for (const f of fs.readdirSync(path.join(root, 'academies'))) {
  if (f.endsWith('.html') && !wanted.has(f)) {
    fs.unlinkSync(path.join(root, 'academies', f));
    console.log(`removed academies/${f} (no matching file in content/academies/)`);
  }
}
